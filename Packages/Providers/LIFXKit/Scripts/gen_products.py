#!/usr/bin/env python3
"""Regenerates Sources/LIFXCodec/LIFXProductTable.swift from LIFX/products products.json.

Usage (from Packages/Providers/LIFXKit):
    curl -sSL -o /tmp/products.json https://raw.githubusercontent.com/LIFX/products/master/products.json
    python3 -I Scripts/gen_products.py /tmp/products.json > Sources/LIFXCodec/LIFXProductTable.swift

Only the fields SmartLights needs are kept (features + temperature range + firmware upgrades).
"""
import json
import sys

FEATURES = [
    ("color", ".color"),
    ("infrared", ".infrared"),
    ("multizone", ".multizone"),
    ("extended_multizone", ".extendedMultizone"),
    ("chain", ".chain"),
    ("matrix", ".matrix"),
    ("hev", ".hev"),
    ("relays", ".relays"),
    ("buttons", ".buttons"),
]


def feature_list(features):
    return "[" + ", ".join(sw for key, sw in FEATURES if features.get(key)) + "]"


def kelvin(features):
    tr = features.get("temperature_range")
    if not tr:
        return "nil"
    return f"{tr[0]}...{tr[1]}"


def swift_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def upgrade(u):
    f = u["features"]
    add = [sw for key, sw in FEATURES if f.get(key) is True]
    parts = [f"major: {u['major']}", f"minor: {u['minor']}"]
    if add:
        parts.append("adds: [" + ", ".join(add) + "]")
    if f.get("temperature_range"):
        tr = f["temperature_range"]
        parts.append(f"kelvin: {tr[0]}...{tr[1]}")
    return "U(" + ", ".join(parts) + ")"


def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    out = []
    out.append("// GENERATED by Scripts/gen_products.py from")
    out.append("// https://raw.githubusercontent.com/LIFX/products/master/products.json")
    out.append("// Do not edit by hand; regenerate instead.")
    out.append("// swift-format-ignore-file")
    out.append("")
    out.append("extension LIFXProduct {")
    out.append("    private typealias U = LIFXProductUpgrade")
    out.append("")
    out.append("    /// Every product known to the LIFX registry (vendor, product id, name, features).")
    out.append("    static let table: [LIFXProduct] = [")
    for vendor in data:
        vid = vendor["vid"]
        defaults = vendor.get("defaults", {})
        for p in vendor["products"]:
            f = dict(defaults)
            f.update(p.get("features", {}))
            ups = [upgrade(u) for u in p.get("upgrades", [])]
            line = (
                f"        LIFXProduct(vendor: {vid}, product: {p['pid']}, name: {swift_string(p['name'])}, "
                f"features: {feature_list(f)}, kelvinRange: {kelvin(f)}"
            )
            if ups:
                line += ", upgrades: [" + ", ".join(ups) + "]"
            line += "),"
            out.append(line)
    out.append("    ]")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
