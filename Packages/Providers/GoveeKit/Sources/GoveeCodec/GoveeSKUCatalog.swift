import Foundation

/// Features of one LAN-capable Govee model.
public struct GoveeLANModel: Sendable, Hashable {
    public var sku: String
    public var rgb: Bool
    public var colorTemperature: Bool
    public var brightness: Bool
    /// Addressable segments (informational; segment control is not implemented).
    public var segments: Int
    /// Kelvin range accepted over LAN.
    public var kelvinRange: ClosedRange<Int>

    public init(sku: String, rgb: Bool, colorTemperature: Bool, brightness: Bool, segments: Int = 0,
                kelvin: ClosedRange<Int> = GoveeLAN.defaultKelvinRange) {
        self.sku = sku
        self.rgb = rgb
        self.colorTemperature = colorTemperature
        self.brightness = brightness
        self.segments = segments
        self.kelvinRange = kelvin
    }

    /// RGB + colour temperature (2000...9000 K) + brightness, no segments.
    public static func basic(_ sku: String) -> GoveeLANModel {
        GoveeLANModel(sku: sku, rgb: true, colorTemperature: true, brightness: true)
    }
}

